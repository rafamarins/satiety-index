function floorAt(id, x) {
  const points = floors[id];
  if (!points) throw new Error(`Missing subject contour: ${id}`);
  for (let i = 1; i < points.length; i++) {
    if (x <= points[i][0]) {
      const [x0, y0] = points[i - 1],
        [x1, y1] = points[i];
      return y0 + (y1 - y0) * Math.max(0, (x - x0) / (x1 - x0));
    }
  }
  return points.at(-1)[1];
}

module.exports = { floorAt, floors };
